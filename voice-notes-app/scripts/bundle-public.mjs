// Packs public/ into src/public.generated.js so the Worker serves the app
// from its own code. Runs automatically before every `wrangler deploy`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, extname } from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml",
  ".png": "image/png", ".webmanifest": "application/manifest+json"
};
const dir = new URL("../public/", import.meta.url).pathname;
const files = {};
for (const name of readdirSync(dir)) {
  const type = TYPES[extname(name)];
  if (!type) continue;
  files["/" + name] = { type, b64: readFileSync(join(dir, name)).toString("base64") };
}
writeFileSync(new URL("../src/public.generated.js", import.meta.url),
  "// Generated by scripts/bundle-public.mjs. Do not edit.\nexport default " + JSON.stringify(files) + ";\n");
console.log(`Bundled ${Object.keys(files).length} files from public/`);
